        private void UpdateTextSuggestions(TextBox textBox, System.Windows.Controls.Primitives.Popup popup, ListBox listBox, IEnumerable<string> source)
        {
            if (_ignoreTextSuggestions || textBox == null || popup == null || listBox == null) return;

            var text = (textBox.Text ?? string.Empty).Trim();
            if (string.IsNullOrWhiteSpace(text))
            {
                popup.IsOpen = false;
                listBox.ItemsSource = null;
                return;
            }

            var matches = (source ?? Enumerable.Empty<string>())
                .Where(x => !string.IsNullOrWhiteSpace(x) &&
                            x.IndexOf(text, System.StringComparison.OrdinalIgnoreCase) >= 0 &&
                            !string.Equals(x.Trim(), text, System.StringComparison.OrdinalIgnoreCase))
                .Take(12)
                .ToList();

            listBox.ItemsSource = matches;
            listBox.SelectedIndex = matches.Count > 0 ? 0 : -1;
            popup.IsOpen = matches.Count > 0;
        }

        private void SuggestionTextBox_LostFocus(object sender, RoutedEventArgs e)
        {
            Dispatcher.BeginInvoke(new System.Action(() =>
            {
                if (BrokerPopup != null) BrokerPopup.IsOpen = false;
                if (FromPopup != null) FromPopup.IsOpen = false;
                if (ToPopup != null) ToPopup.IsOpen = false;
            }), DispatcherPriority.Background);
        }

        private void SuggestionTextBox_PreviewKeyDown(object sender, KeyEventArgs e)
        {
            var textBox = sender as TextBox;
            if (textBox == null) return;

            System.Windows.Controls.Primitives.Popup popup;
            ListBox listBox;
            ResolveSuggestionControls(textBox, out popup, out listBox);
            if (popup == null || listBox == null || !popup.IsOpen || listBox.Items.Count == 0) return;

            if (e.Key == Key.Down)
            {
                if (listBox.SelectedIndex < listBox.Items.Count - 1)
                {
                    listBox.SelectedIndex++;
                    listBox.ScrollIntoView(listBox.SelectedItem);
                }
                e.Handled = true;
            }
            else if (e.Key == Key.Up)
            {
                if (listBox.SelectedIndex > 0)
                {
                    listBox.SelectedIndex--;
                    listBox.ScrollIntoView(listBox.SelectedItem);
                }
                e.Handled = true;
            }
            else if (e.Key == Key.Enter || e.Key == Key.Tab)
            {
                var selected = listBox.SelectedItem as string;
                if (!string.IsNullOrWhiteSpace(selected))
                {
                    ApplySuggestion(textBox, popup, selected);
                    e.Handled = true;
                }
            }
            else if (e.Key == Key.Escape)
            {
                popup.IsOpen = false;
                e.Handled = true;
            }
        }

