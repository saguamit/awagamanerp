        private void ConfigureDebounceTimers()
        {
            _vehicleSuggestionTimer.Tick += VehicleSuggestionTimer_Tick;
            Closed += (s, e) => _vehicleSuggestionTimer.Stop();
        }

        private void LoadSuggestionSources()
        {
            try
            {
                var entries = (_repository?.GetAll() ?? _allEntries ?? new List<ChallanEntry>())
                    .Where(x => x != null)
                    .ToList();

                _brokerNames = entries
                    .Select(x => (x.BrokerName ?? string.Empty).Trim())
                    .Where(x => !string.IsNullOrWhiteSpace(x))
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .OrderBy(x => x)
                    .ToList();

                _fromPlaces = entries
                    .Select(x => (x.From ?? string.Empty).Trim())
                    .Where(x => !string.IsNullOrWhiteSpace(x))
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .OrderBy(x => x)
                    .ToList();

                _toPlaces = entries
                    .Select(x => (x.To ?? string.Empty).Trim())
                    .Where(x => !string.IsNullOrWhiteSpace(x))
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .OrderBy(x => x)
                    .ToList();
            }
            catch
            {
                _brokerNames = new List<string>();
                _fromPlaces = new List<string>();
                _toPlaces = new List<string>();
            }
        }

