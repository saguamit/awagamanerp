        private void Save_Click(object sender, RoutedEventArgs e)
        {
            CommitDatePickerBindings();
            NormalizeChallanNumberInForm();
            if (string.IsNullOrWhiteSpace(Result.ChallanNumber))
            {
                MessageBox.Show("Challan Number cannot be empty.", "Validation Error", MessageBoxButton.OK, MessageBoxImage.Warning);
                return;
            }

            if (string.IsNullOrWhiteSpace(Result.BrokerName))
            {
                MessageBox.Show("Agent / Broker is mandatory.", "Validation Error", MessageBoxButton.OK, MessageBoxImage.Warning);
                return;
            }

            if (string.IsNullOrWhiteSpace(Result.From))
            {
                MessageBox.Show("From is mandatory.", "Validation Error", MessageBoxButton.OK, MessageBoxImage.Warning);
                return;
            }

            if (string.IsNullOrWhiteSpace(Result.To))
            {
                MessageBox.Show("To is mandatory.", "Validation Error", MessageBoxButton.OK, MessageBoxImage.Warning);
                return;
            }

            try
            {
                var dup = _repository.FindByChallanNumber(Result.ChallanNumber);
                if (dup != null && dup.Sr != _editingSr)
                {
                    MessageBox.Show($"Challan Number '{Result.ChallanNumber}' already exists.", "Duplicate Error", MessageBoxButton.OK, MessageBoxImage.Error);
                    return;
                }
            }
            catch (System.Exception ex)
            {
                AppLogger.LogException(nameof(Save_Click), ex);
            }

            if (!string.IsNullOrWhiteSpace(Result.LRNumber))
            {
                var inputLRs = Result.LRNumber
                    .Split(new[] { ',', '\n', '\r' }, System.StringSplitOptions.RemoveEmptyEntries)
                    .Select(s => s.Trim())
                    .Where(s => !string.IsNullOrWhiteSpace(s))
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .ToList();

                var entriesForValidation = (_repository?.GetAll() ?? _allEntries ?? new List<ChallanEntry>())
                    .Where(x => x != null && x.Sr != _editingSr && !string.IsNullOrWhiteSpace(x.LRNumber))
                    .ToList();

                foreach (var other in entriesForValidation)
                {
                    var otherLRs = (other.LRNumber ?? string.Empty)
                        .Split(new[] { ',', '\n', '\r' }, System.StringSplitOptions.RemoveEmptyEntries)
                        .Select(s => s.Trim());
                    var overlap = inputLRs.Intersect(otherLRs, System.StringComparer.OrdinalIgnoreCase).FirstOrDefault();
                    if (overlap != null)
                    {
                        MessageBox.Show($"LR Number '{overlap}' is already used in Challan '{other.ChallanNumber}'.", "Duplicate Error", MessageBoxButton.OK, MessageBoxImage.Error);
                        return;
                    }
                }
            }

            Result.RecalculateBalance();
            WasSaved = true;
            if (System.Windows.Interop.ComponentDispatcher.IsThreadModal)
            {
                DialogResult = true;
            }
            Close();
        }

        private void CommitDatePickerBindings()
        {
            UpdateDatePickerBinding(ChallanDatePicker);
            UpdateDatePickerBinding(AdvanceDatePicker);
            UpdateDatePickerBinding(BalancePaidDatePicker);
        }

        private static void UpdateDatePickerBinding(DatePicker picker)
        {
            if (picker == null) return;
            try
            {
                var binding = picker.GetBindingExpression(DatePicker.SelectedDateProperty);
                binding?.UpdateSource();
            }
            catch
            {
            }
        }

        private void NormalizeChallanNumberInForm()
        {
            if (Result == null)
            {
                return;
            }

            var normalized = ChallanNumberFormatter.Normalize(Result.ChallanNumber, Result.Date);
            if (!string.Equals(Result.ChallanNumber, normalized, System.StringComparison.Ordinal))
            {
                Result.ChallanNumber = normalized;
            }
        }

        private void AutoFillNextChallanNumber(bool force = false)
        {
            if (!_isNewEntry || Result == null)
            {
                return;
            }

            var current = (Result.ChallanNumber ?? string.Empty).Trim();
            if (!force &&
                current.Length > 0 &&
                !string.Equals(current, _lastAutoGeneratedChallanNumber, System.StringComparison.OrdinalIgnoreCase))
            {
                return;
            }

            var challanDate = Result.Date == default(System.DateTime)
                ? System.DateTime.Today
                : Result.Date;
            var nextNumber = BuildNextChallanNumber(challanDate);
            _lastAutoGeneratedChallanNumber = nextNumber;
            Result.ChallanNumber = nextNumber;
        }

        private string BuildNextChallanNumber(System.DateTime challanDate)
        {
            try
            {
                var fyStart = ChallanNumberFormatter.GetFinancialYearStart(challanDate);
                var challanLedgerRepository = new ChallanRepository { LedgerMode = "Challan" };
                var fySuffix = ChallanNumberFormatter.GetFinancialYearSuffix(challanDate);
                var latestRow = challanLedgerRepository
                    .SearchAdvanced(fySuffix, string.Empty, string.Empty, string.Empty, 1, 1, "ChallanNumber", false, true)
                    .FirstOrDefault();
                var nextSequence = latestRow != null &&
                                   ChallanNumberFormatter.GetFinancialYearStart(latestRow.ChallanNumber, latestRow.Date) == fyStart
                    ? ChallanNumberFormatter.GetSequence(latestRow.ChallanNumber) + 1
                    : 1;

                return ChallanNumberFormatter.Normalize(nextSequence.ToString(), challanDate);
            }
            catch (System.Exception ex)
            {
                AppLogger.LogException(nameof(BuildNextChallanNumber), ex);
                return ChallanNumberFormatter.Normalize("1", challanDate);
            }
        }

