        private void SuggestionList_PreviewMouseLeftButtonDown(object sender, MouseButtonEventArgs e)
        {
            var listBox = sender as ListBox;
            if (listBox == null) return;

            var dependencyObject = e.OriginalSource as DependencyObject;
            while (dependencyObject != null && !(dependencyObject is ListBoxItem))
            {
                dependencyObject = VisualTreeHelper.GetParent(dependencyObject);
            }

            var item = dependencyObject as ListBoxItem;
            if (item == null) return;

            var selected = item.DataContext as string;
            if (string.IsNullOrWhiteSpace(selected)) return;

            if (ReferenceEquals(listBox, BrokerSuggestionList))
            {
                ApplySuggestion(BrokerNameBox, BrokerPopup, selected);
            }
            else if (ReferenceEquals(listBox, FromSuggestionList))
            {
                ApplySuggestion(FromBox, FromPopup, selected);
            }
            else if (ReferenceEquals(listBox, ToSuggestionList))
            {
                ApplySuggestion(ToBox, ToPopup, selected);
            }

            e.Handled = true;
        }

        private void ResolveSuggestionControls(TextBox textBox, out System.Windows.Controls.Primitives.Popup popup, out ListBox listBox)
        {
            popup = null;
            listBox = null;

            if (ReferenceEquals(textBox, BrokerNameBox))
            {
                popup = BrokerPopup;
                listBox = BrokerSuggestionList;
            }
            else if (ReferenceEquals(textBox, FromBox))
            {
                popup = FromPopup;
                listBox = FromSuggestionList;
            }
            else if (ReferenceEquals(textBox, ToBox))
            {
                popup = ToPopup;
                listBox = ToSuggestionList;
            }
        }

        private void ApplySuggestion(TextBox textBox, System.Windows.Controls.Primitives.Popup popup, string value)
        {
            if (textBox == null) return;

            _ignoreTextSuggestions = true;
            try
            {
                textBox.Text = value ?? string.Empty;
                textBox.CaretIndex = textBox.Text.Length;
                if (popup != null) popup.IsOpen = false;
            }
            finally
            {
                _ignoreTextSuggestions = false;
            }
        }

        private void ApplyVehicleSelection(VehicleEntry v)
        {
            if (Result == null || v == null) return;
            Result.VehicleNumber = (v.VehicleNumber ?? string.Empty).Trim().ToUpperInvariant();
            Result.OwnerName = v.OwnerName;
            Result.PAN = v.PANNumber;
            Result.EngineNo = v.EngineNumber;
            Result.ChassisNo = v.ChassisNumber;
            Result.VehicleType = v.VehicleType;
            Result.DriverName = v.DriverName;
            Result.DriverMobile = v.DriverMobile;
            Result.LicenceNo = v.LicenceNumber;
            Result.PolicyNo = v.PolicyNumber;
        }

